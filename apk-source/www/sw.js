/* TimeBalance Service Worker - PWA */
const CACHE_NAME = 'timebalance-pwa-v1';
const SHELL = [
  './',
  './index.html',
  './style.css',
  './manifest.json',
  './tb-config.js',
  './tb-auth.js',
  './app.js',
  './pwa.js',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-maskable-512.png'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys.filter(key => key !== CACHE_NAME).map(key => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  // HTML/JS/config/auth should prefer the network so token/login changes are not stuck in cache.
  const pathname = new URL(request.url).pathname;
  const dynamic = /\/(index\.html|app\.js|tb-auth\.js|tb-config\.js|pwa\.js)$/.test(pathname);

  if (dynamic) {
    event.respondWith(
      fetch(request)
        .then(response => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
          return response;
        })
        .catch(() => caches.match(request))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(cached => cached || fetch(request).then(response => {
      const copy = response.clone();
      caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
      return response;
    }))
  );
});
